import {test,expect} from "@playwright/test";
test("two synthetic items reveal provisional pattern; teacher can reject without changing responses",async({page})=>{
 await page.goto("/login");
 await page.getByLabel("Email",{exact:true}).fill("guru@numeriq.test");
 await page.getByLabel("Kata sandi",{exact:true}).fill(process.env.NUMERIQ_DEMO_PASSWORD!);
 await page.getByRole("button",{name:"Masuk",exact:false}).click();
 await expect(page).toHaveURL(/\/teacher$/);
 await page.goto("/teacher/assessments");
 await expect(page.getByRole("heading",{name:"Asesmen numerasi"})).toBeVisible();
 const panel=page.locator("article.panel").filter({has:page.getByRole("heading",{name:"Nara Demo"})});
 const existing=await panel.locator('a[href^="/teacher/assessments/"]').evaluateAll(nodes=>nodes.map(n=>n.getAttribute("href")));
 await panel.getByLabel("Paket sintetis").selectOption("pattern-demo");
 await panel.getByRole("button",{name:"Tugaskan paket demo"}).click();
 await expect(page).toHaveURL(/\/teacher\/assessments$/);
 await expect.poll(async()=>panel.locator('a[href^="/teacher/assessments/"]').count()).toBeGreaterThan(existing.length);
 const links=await panel.locator('a[href^="/teacher/assessments/"]').evaluateAll(nodes=>nodes.map(n=>n.getAttribute("href")));
 const reportPath=links.find(link=>!existing.includes(link));expect(reportPath).toBeTruthy();
 const sessionId=reportPath!.split("/").pop();
 await page.goto("/teacher");
 await page.locator(".child-card").filter({hasText:"Nara Demo"}).getByRole("button",{name:"Buka ruang anak"}).click();
 await page.goto("/student/assessments/"+sessionId);
 await page.getByRole("radio",{name:"5",exact:true}).check();
 await page.getByRole("button",{name:"Simpan dan lanjut"}).click();
 await expect(page.getByText("1/2 tersimpan")).toBeVisible();
 await page.getByRole("radio",{name:"6",exact:true}).check();
 await page.getByRole("button",{name:"Simpan dan lanjut"}).click();
 await expect(page.getByRole("heading",{name:"Terima kasih sudah mencoba!"})).toBeVisible();
 await page.getByText("Kembali ke ruang pendamping",{exact:true}).click();
 await page.getByLabel("Kata sandi pendamping").fill(process.env.NUMERIQ_DEMO_PASSWORD!);
 await page.getByRole("button",{name:"Verifikasi dan kembali"}).click();
 await page.goto(reportPath!);
 await expect(page.locator("article.panel")).toHaveCount(2);
 await expect(page.locator("article.panel").first()).toContainText("PLACE_VALUE_COMPOSE");
 await page.getByRole("link",{name:"Lihat bukti pola dan estimasi"}).click();
 const pattern=page.locator("article.panel").filter({has:page.getByRole("heading",{name:/PLACE_VALUE_COMPOSE/})});
 await expect(pattern).toContainText("Perlu ditinjau guru");
 await expect(pattern).toContainText("2 soal berbeda");
 await pattern.getByLabel("Keputusan guru").selectOption("rejected");
 await pattern.getByLabel("Alasan berdasarkan bukti").fill("Guru belum melihat konsistensi pola pada kegiatan kelas.");
 await pattern.getByRole("button",{name:"Simpan tinjauan"}).click();
 await expect(pattern).toContainText("Ditolak guru");
 await page.goto(reportPath!);
 await expect(page.locator("article.panel").first()).toContainText("Opsi: five");
 await expect(page.locator("article.panel").nth(1)).toContainText("Opsi: six");
});
